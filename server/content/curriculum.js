// Flattened list of lesson rows ready for insertion.
export function seedLessons() {
  const rows = [];
  const seq = {};
  const next = (subject, level) => (seq[`${subject}:${level}`] = (seq[`${subject}:${level}`] || 0) + 1);
  for (const [level, gen, title, body, example] of MATH_LOGIC) {
    const subject = gen.split('.')[0];
    rows.push({ subject, level, seq: next(subject, level), gen, topic: null, title, body, example });
  }
  for (const subject of Object.keys(LANGUAGE_SUBJECTS)) {
    for (const [level, topic, title] of TOPICS) {
      rows.push({ subject, level, seq: next(subject, level), gen: 'vocab', topic, title, body: VOCAB_BODY, example: '' });
    }
  }
  return rows.map((r) => ({ ...r, is_free: r.seq === 1 ? 1 : 0 }));
}
